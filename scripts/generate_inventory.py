#!/usr/bin/env python3
"""Generate SSH config and Ansible inventory from real Terraform output, no hardcoded IPs."""
import json
import os
import pathlib
import shlex
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
GEN = ROOT / "generated"
KEY = pathlib.Path.home() / ".ssh" / "mern_hero_vired"


def main():
    if not KEY.exists():
        sys.exit(f"Missing SSH private key {KEY}. Run: bash scripts/prepare.sh")
    result = subprocess.run(
        ["terraform", f"-chdir={ROOT / 'terraform'}", "output", "-json"],
        capture_output=True, text=True, check=True,
    )
    data = json.loads(result.stdout)
    def val(name):
        return str(data[name]["value"])

    web_public = val("web_public_ip")
    web_private = val("web_private_ip")
    db_private = val("database_private_ip")
    ssh_cidr = val("allowed_ssh_cidr")
    if not web_public or not db_private:
        sys.exit("Terraform has no EC2 IP outputs. Complete terraform apply first.")
    GEN.mkdir(parents=True, exist_ok=True)
    os.chmod(GEN, 0o700)
    conf = GEN / "ssh_config"
    conf.write_text(f"""# Generated by scripts/generate_inventory.py. Never add this file to Git.
Host travelmemory-web
    HostName {web_public}
    User ubuntu
    IdentityFile {KEY}
    IdentitiesOnly yes
    StrictHostKeyChecking accept-new
    ServerAliveInterval 30

Host travelmemory-db
    HostName {db_private}
    User ubuntu
    IdentityFile {KEY}
    IdentitiesOnly yes
    StrictHostKeyChecking accept-new
    ProxyCommand ssh -F {conf} -W %h:%p travelmemory-web
    ServerAliveInterval 30
""")
    os.chmod(conf, 0o600)
    inventory = GEN / "inventory.ini"
    inventory.write_text(f"""[web]
web ansible_host=travelmemory-web public_ip={web_public} private_ip={web_private}

[database]
database ansible_host=travelmemory-db private_ip={db_private}

[all:vars]
ansible_user=ubuntu
ansible_ssh_private_key_file={KEY}
ansible_ssh_common_args='-F {conf}'
ansible_python_interpreter=/usr/bin/python3
allowed_ssh_cidr={ssh_cidr}
""")
    os.chmod(inventory, 0o600)
    print(f"Generated: {conf}")
    print(f"Generated: {inventory}")
    print(f"Web public IPv4: {web_public}")
    print(f"Database private IPv4: {db_private}")
    print("Smoke check: ssh -F generated/ssh_config travelmemory-web hostname")
    print("Smoke check: ssh -F generated/ssh_config travelmemory-db hostname")

if __name__ == "__main__":
    main()
